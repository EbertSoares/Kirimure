import { chromium } from '@playwright/test';
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('console', (m) => console.log('CONSOLE', m.type(), m.text()));
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await page.goto('http://127.0.0.1:8080/', { waitUntil: 'networkidle' });
console.log('before', await page.evaluate(() => ({ root: document.getElementById('app-root')?.innerHTML.slice(0, 100), count: document.querySelectorAll('g.state.available').length })));
const loc = page.locator('g.state.available');
console.log('count', await loc.count());
console.log('box', await loc.first().boundingBox());
await loc.first().click();
await page.waitForTimeout(2500);
console.log('after', await page.evaluate(() => ({ text: document.body.innerText.slice(0, 200), map: !!document.querySelector('.map-screen'), app: !!document.querySelector('.simulation-app'), html: document.getElementById('app-root')?.innerHTML.slice(0, 200) })));
await page.screenshot({ path: '/tmp/kirimure-qa/click-test.png' });
await browser.close();
